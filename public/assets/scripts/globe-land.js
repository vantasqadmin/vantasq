// Great-circle point between unit vectors a and b, lifted off the surface
// in the middle so long routes arc visibly above the globe.
export function arcPoint(a, b, omega, t) {
  const s = Math.sin(omega);
  const k1 = Math.sin((1 - t) * omega) / s;
  const k2 = Math.sin(t * omega) / s;
  const lift = 1 + Math.sin(Math.PI * t) * 0.12 * Math.min(1.6, omega);
  return [(a[0] * k1 + b[0] * k2) * lift, (a[1] * k1 + b[1] * k2) * lift, (a[2] * k1 + b[2] * k2) * lift];
}

export function angleBetween(a, b) {
  return Math.acos(Math.max(-1, Math.min(1, a[0] * b[0] + a[1] * b[1] + a[2] * b[2])));
}

