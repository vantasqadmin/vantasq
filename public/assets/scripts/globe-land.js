const D = Math.PI / 180;

export function toVec(lat, lon) {
  const cl = Math.cos(lat * D);
  return [cl * Math.sin(lon * D), Math.sin(lat * D), cl * Math.cos(lon * D)];
}

function inside(lon, lat, poly) {
  let hit = false;
  for (let i = 0, j = poly.length - 1; i < poly.length; j = i++) {
    const [xi, yi] = poly[i];
    const [xj, yj] = poly[j];
    if ((yi > lat) !== (yj > lat) && lon < ((xj - xi) * (lat - yi)) / (yj - yi) + xi) hit = !hit;
  }
  return hit;
}

// Land sampled on a grid that widens in longitude towards the poles, so the
// dots stay evenly spaced on the sphere.
export function sampleLand(step) {
  const out = [];
  for (let lat = -56; lat <= 82; lat += step) {
    const lonStep = step / Math.max(0.22, Math.cos(lat * D));
    for (let lon = -180; lon < 180; lon += lonStep) {
      if (POLYS.some((p) => inside(lon, lat, p))) out.push(...toVec(lat, lon));
    }
  }
  return new Float32Array(out);
}

